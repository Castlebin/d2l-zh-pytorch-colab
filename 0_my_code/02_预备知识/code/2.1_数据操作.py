torch.cat((X, Y), dim=0), torch.cat((X, Y), dim=1)

# %% 逻辑运算符（>、<、==）会对张量中的元素进行逐元素的比较，并返回一个包含布尔值的张量。
X == Y



# %% 对张量中的所有元素进行求和，会返回一个包含单个元素的张量。
X.sum()


