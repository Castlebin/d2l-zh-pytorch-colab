### 2.1.3. 广播机制
#%%
# 不同形状的张量可以通过广播机制进行运算
a = torch.arange(3).reshape((3, 1))
b = torch.arange(2).reshape((1, 2))

print("a的形状:", a.shape)
print(a)
print("\nb的形状:", b.shape)
print(b)

print("\na + b (广播机制):")
print(a + b)

# 可以看到，它是将两个矩阵维度扩展后相加
#在上面的部分中，我们看到了如何在相同形状的两个张量上执行按元素操作。
# 在某些情况下，即使形状不同，我们仍然可以通过调用 广播机制（broadcasting mechanism）来执行按元素操作。
# 这种机制的工作方式如下：
# 1. 通过适当复制元素来扩展一个或两个数组，以便在转换之后，两个张量具有相同的形状；
# 2. 对生成的数组执行按元素操作。

#由于 a 和 b是不同行数和列数的，
# 如果让它们相加，它们的形状不匹配。 我们将两个矩阵广播为一个更大的矩阵，
# 如下所示：矩阵 a 将复制列， 矩阵 b 将复制行。
# 然后再按元素相加。
'''
a 原来是：tensor([
        [0],
        [1],
        [2]])
        
通过广播机制，复制列后变为：tensor([        
        [0, 0],
        [1, 1],
        [2, 2]])

b 原来是：tensor([[0, 1]])
通过广播机制，复制行后变为：tensor([
        [0, 1],
        [0, 1],
        [0, 1]])
        
所以 a + b 结果为变为了一个 3 行 2 列 的矩阵：
tensor([
        [0, 1],
        [1, 2],
        [2, 3]])
'''


# 2.1.4. 索引和切片
#%%
'''
就像在任何其他Python数组中一样，张量中的元素可以通过索引访问。 
与任何Python数组一样：第一个元素的索引是0，最后一个元素索引是-1； 可以指定范围以包含第一个元素和最后一个之前的元素。
如下所示，我们可以用[-1]选择最后一个元素，可以用[1:3]选择第二个和第三个元素：
'''
X = torch.arange(12).reshape((3,4))
print(X)
print('X[-1]=', X[-1])      # 选择最后一行
print('X[1:3]=', X[1:3])     # 选择第2-3行
print('X[1:3, 0:3]=', X[1:3, 0:3])  # 选择第2-3行，第1-3列


# 2.1.5 节省内存
#%% 内存管理与运算
'''
运行一些操作可能会导致为新结果分配内存。 例如，如果我们用Y = X + Y，我们将取消引用Y指向的张量，而是指向新分配的内存处的张量。

在下面的例子中，我们用Python的id()函数演示了这一点， 它给我们提供了内存中引用对象的确切地址。 

运行Y = Y + X后，我们会发现id(Y)指向另一个位置。 这是因为Python首先计算Y + X，为结果分配新的内存，然后使Y指向内存中的这个新位置。
'''
X = torch.ones((2, 3))
Y = torch.zeros((2, 3))
# 查看内存地址
before = id(Y)
Y = Y + X
print("内存地址改变:", id(Y) != before)

# 原地操作(不分配新内存)
Z = torch.zeros_like(Y)
print("原地操作前 ID:", id(Z))
Z[:] = X + Y
print("原地操作后 ID:", id(Z))

# 使用 += 等操作也是原地的
before = id(X)
X += Y
print("\n使用 += 后 ID 不变:", id(X) == before)


