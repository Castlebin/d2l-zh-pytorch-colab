### 2.1.5. 节省内存
'''
运行一些操作可能会导致为新结果分配内存。 例如，如果我们用Y = X + Y，我们将取消引用 Y 原先指向的张量，然后指向新分配的内存处的张量。

在下面的例子中，我们用Python的id()函数演示了这一点， 它给我们提供了内存中引用对象的确切地址。 运行Y = Y + X后，我们会发现id(Y)指向另一个位置。 这是因为Python首先计算Y + X，为结果分配新的内存，然后使Y指向内存中的这个新位置。
'''
before = id(Y)
Y = Y + X
id(Y) == before   # False

'''
这可能是不可取的，原因有两个：

1. 首先，我们不想总是不必要地分配内存。在机器学习中，我们可能有数百兆的参数，并且在一秒内多次更新所有参数。通常情况下，我们希望原地执行这些更新；
2. 如果我们不原地更新，其他引用仍然会指向旧的内存位置，这样我们的某些代码可能会无意中引用旧的参数。
'''


# %%
# 在下面的例子中，我们使用了Y[:] = Y + X来原地更新Y。 这一次，id(Y)没有改变，因为我们没有分配新的内存。
before = id(Y)
Y[:] = Y + X
id(Y) == before   # True



# %% 也可以使用 X += Y 这种方式来减少操作的内存开销
before = id(X)
X += Y
id(X) == before   # True


